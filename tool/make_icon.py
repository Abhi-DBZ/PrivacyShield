"""Writes Privacy Shield's launcher, themed (monochrome) and notification icons as Android vector
drawables. Design "B · Blinds" (picked 2026-11-25): four privacy-louver slats in four indigo tones,
slanted, their widths following a circle. No background plate (transparent, same as Icon Mixer).
Recipe: D:\\TestPY\\App\\DESIGN-GUIDE.md.

Run from the project root:  python tool/make_icon.py
"""
import math
import os

RES = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res", "drawable")

BG = "#00000000"                                          # transparent: no plate
SLATS = ["#FF1E2A7A", "#FF3D4FC4", "#FF6F80E0", "#FFA9B5F2"]   # top → bottom
REACH = 26.5        # max distance of any point from the centre (54,54) on the 108 canvas
HEIGHT = 7.0        # slat thickness
PITCH = 11.0        # slat spacing (centre to centre)
SLANT = 2.0         # how far the bottom edge is shifted left (the louver tilt)


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def slats():
    paths = []
    for i in range(4):
        cy = 54 + (i - 1.5) * PITCH
        top, bottom = cy - HEIGHT / 2, cy + HEIGHT / 2
        far = max(abs(top - 54), abs(bottom - 54))
        half = math.floor((math.sqrt(REACH ** 2 - far ** 2) - SLANT / 2) * 10) / 10
        # Inner/outer slats get the same width rule, so the four together read as a circle.
        x0, x1 = 54 - half + SLANT / 2, 54 + half + SLANT / 2
        paths.append(f"M{f(x0)},{f(top)} H{f(x1)} L{f(x1 - SLANT)},{f(bottom)} H{f(x0 - SLANT)} Z")
    return paths


def vector(paths, size="108dp", viewport=108, group=""):
    body = "".join(f'\n        <path android:fillColor="{c}" android:pathData="{d}" />' for d, c in paths)
    open_g, close_g = (f"\n    <group{group}>", "\n    </group>") if group else ("", "")
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Generated by tool/make_icon.py — edit that, not this file. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}" android:height="{size}"\n'
            f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">'
            f'{open_g}{body}{close_g}\n</vector>\n')


def main():
    p = slats()
    write("ic_launcher_foreground.xml", vector(list(zip(p, SLATS))))
    # Themed icons: the system tints this layer (only alpha matters); gaps keep the slats apart.
    write("ic_launcher_monochrome.xml", vector([(d, "#FF000000") for d in p]))
    write("ic_notification.xml", vector([(d, "#FFFFFFFF") for d in p], size="24dp", viewport=54,
                                        group=' android:translateX="-27" android:translateY="-27"'))
    write("ic_launcher_background.xml",
          '<?xml version="1.0" encoding="utf-8"?>\n<shape xmlns:android="http://schemas.android.com/apk/res/android" '
          'android:shape="rectangle">\n    <solid android:color="' + BG + '" />\n</shape>\n')


def write(name, text):
    with open(os.path.join(RES, name), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", name)


if __name__ == "__main__":
    main()
